-- ==============================================================================
-- CRIAÇÃO DA TABELA E ESTRUTURAS DO MÓDULO "GASTOS" (ISOLAMENTO CONTÁBIL TOTAL)
-- ==============================================================================
-- Onde executar: Supabase Dashboard -> SQL Editor -> Run
-- Motivo Técnico: Armazenar os lançamentos independentes das categorias
-- Restaurante, Lazer e Conveniência, garantindo persistência real, precisão
-- de 2 casas decimais e isolamento financeiro das regras de saldo/despesas.

-- 1. Criação da tabela gastos_itens
CREATE TABLE IF NOT EXISTS public.gastos_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(30) NOT NULL CHECK (categoria IN ('Restaurante', 'Lazer', 'Conveniência')),
    valor NUMERIC(10, 2) NOT NULL CHECK (valor > 0),
    mes_referencia VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Índices para otimização de consultas por mês e categoria
CREATE INDEX IF NOT EXISTS idx_gastos_itens_mes_referencia ON public.gastos_itens (mes_referencia);
CREATE INDEX IF NOT EXISTS idx_gastos_itens_categoria ON public.gastos_itens (categoria);
CREATE INDEX IF NOT EXISTS idx_gastos_itens_mes_cat ON public.gastos_itens (mes_referencia, categoria);
CREATE INDEX IF NOT EXISTS idx_gastos_itens_created_at ON public.gastos_itens (created_at DESC);

-- 3. Habilitação de RLS (Row Level Security)
ALTER TABLE public.gastos_itens ENABLE ROW LEVEL SECURITY;

-- 4. Políticas de RLS para anon e authenticated (leitura, escrita, exclusão)
CREATE POLICY "Permitir leitura de gastos para todos" 
ON public.gastos_itens 
FOR SELECT 
TO anon, authenticated 
USING (true);

CREATE POLICY "Permitir inserção de gastos para todos" 
ON public.gastos_itens 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

CREATE POLICY "Permitir atualização de gastos para todos" 
ON public.gastos_itens 
FOR UPDATE 
TO anon, authenticated 
USING (true);

CREATE POLICY "Permitir exclusão de gastos para todos" 
ON public.gastos_itens 
FOR DELETE 
TO anon, authenticated 
USING (true);
