-- ==============================================================================
-- AJUSTE E CRIAÇÃO DEFINITIVA DA TABELA gastos_itens (SUPABASE)
-- ==============================================================================
-- Onde executar: Supabase Dashboard -> SQL Editor -> Run
-- Motivo Técnico: Criar e garantir a existência da tabela gastos_itens com
-- permissão total para as roles 'anon', 'authenticated' e 'service_role', 
-- evitando que requisições externas da API ou Vercel sejam bloqueadas por RLS.

-- 1. Criação da tabela (caso ainda não exista)
CREATE TABLE IF NOT EXISTS public.gastos_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(30) NOT NULL CHECK (categoria IN ('Restaurante', 'Lazer', 'Conveniência')),
    valor NUMERIC(10, 2) NOT NULL CHECK (valor > 0),
    mes_referencia VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Índices de busca de alta performance por mês e categoria
CREATE INDEX IF NOT EXISTS idx_gastos_itens_mes_referencia ON public.gastos_itens (mes_referencia);
CREATE INDEX IF NOT EXISTS idx_gastos_itens_categoria ON public.gastos_itens (categoria);
CREATE INDEX IF NOT EXISTS idx_gastos_itens_mes_cat ON public.gastos_itens (mes_referencia, categoria);
CREATE INDEX IF NOT EXISTS idx_gastos_itens_created_at ON public.gastos_itens (created_at DESC);

-- 3. Habilitação de RLS e Concessão Completa de Acesso (Zero Bloqueio)
ALTER TABLE public.gastos_itens ENABLE ROW LEVEL SECURITY;

-- Limpeza de políticas prévias se existirem
DROP POLICY IF EXISTS "Permitir leitura de gastos para todos" ON public.gastos_itens;
DROP POLICY IF EXISTS "Permitir inserção de gastos para todos" ON public.gastos_itens;
DROP POLICY IF EXISTS "Permitir atualização de gastos para todos" ON public.gastos_itens;
DROP POLICY IF EXISTS "Permitir exclusão de gastos para todos" ON public.gastos_itens;
DROP POLICY IF EXISTS "Acesso total gastos_itens" ON public.gastos_itens;

-- Política definitiva permitindo SELECT, INSERT, UPDATE, DELETE para todas as chamadas
CREATE POLICY "Acesso total gastos_itens"
ON public.gastos_itens
FOR ALL
TO public, anon, authenticated, service_role
USING (true)
WITH CHECK (true);

-- Concessão explícita de permissões DML para as roles anon e authenticated
GRANT ALL ON TABLE public.gastos_itens TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
